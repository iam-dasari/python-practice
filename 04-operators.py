#Operators in Python

#Airthmetic Operators
print("Airthmetic Operators")
x=11
y=5
print(f"x={x} ; y={y}")
print(f"x+y={x+y} ; x-y={x-y} ; x*y={x*y=} ; x/y={x/y} ; x//y={x//y}")

#Comparision Operators
print("Comparision Operators")
a=10
b=5
print(f"a={a} ; b={b}")
print(f"a>b={a>b} ; a<b={a<b} ; (a==b)={a==b} ; (a!=b)={a!=b}")

#Logical Operators
print("Logical Operators")
a=True
b=False
print(f"a={a} ; b={b}")
print(f"a and b={a and b} ; a or b={a or b} ; not a={not a}")

#Assignment Operators
print("Assignment Operators")
x=5
print(f"x={x}")
x+=5
print(f"x+=5={x}")
x-=5
print(f"x-=5={x}")
x*=5
print(f"x*=5={x}")
x/=5
print(f"x/=5={x}")
